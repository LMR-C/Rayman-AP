"""Base class of the Rayman generation tests.

Generated by Claude (Anthropic AI assistant).
"""
from BaseClasses import CollectionState
from test.bases import WorldTestBase


class RaymanTestBase(WorldTestBase):
    game = "Rayman"

    def state_with(self, *item_names: str) -> CollectionState:
        """State holding only the given items (one copy each), plus the level events they unlock."""
        state = CollectionState(self.multiworld)
        for name in item_names:
            state.collect(self.world.create_item(name), prevent_sweep=True)
        state.sweep_for_advancements()   # collects the "... finished event item" reachable with those items
        return state

    def state_without(self, *item_names: str) -> CollectionState:
        """State holding every item of the pool except the given ones, plus the events reachable with them.

        Unlike collect_all_but, the locked events (level finished, victory) are not collected directly:
        they are only earned if their location can be reached.
        """
        state = CollectionState(self.multiworld)
        for item in self.multiworld.itempool:
            if item.name not in item_names:
                state.collect(item, prevent_sweep=True)
        state.sweep_for_advancements()
        return state

    def reach_location(self, state: CollectionState, name: str) -> bool:
        return state.can_reach(name, "Location", self.player)

    def reach_region(self, state: CollectionState, name: str) -> bool:
        return state.can_reach(name, "Region", self.player)
