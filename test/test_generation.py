from collections import Counter

from Fill import distribute_items_restrictive

from ..items import TRAP_ITEMS
from .bases import RaymanTestBase

POWERS = ("Telescopic Fist", "Hanging", "Grappling Fist", "Helicopter", "Run")
FILLERS = {"Simple Power", "Double Power", "Big Power", "Life Status", "5 tings"}

DEFAULT_LOCATIONS = 32    # 3 Betilla + 2 Moskito + 3 level finished + 24 cages
LIFE_STATUS_LOCATIONS = 13
MAGICIAN_LOCATIONS = 4

LIFE_AND_MAGICIAN = {"include_life_status_in_location": True, "include_magician_challenges_in_location": True}
TRAPS_ON = {"trap_fill_percentage": 50, "reversed_controls_weight": "medium", "forced_run_weight": "high"}


def is_trap_forbidden(location_id: int) -> bool:
    """Moskito (3xxx) and level finished (7xxx) locations never hold a trap."""
    return 3000 <= location_id <= 3999 or 7000 <= location_id <= 7999


class RaymanGenerationBase(RaymanTestBase):
    def real_locations(self):
        """Locations of the data package (the events have no id)."""
        return [loc for loc in self.multiworld.get_locations(self.player) if loc.address is not None]

    def pool_names(self) -> Counter:
        return Counter(item.name for item in self.multiworld.itempool)


