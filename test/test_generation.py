# ---- C3: traps are never placed on Moskito / level finished locations

class TestTrapItemRule(RaymanGenerationBase):
    options = {**LIFE_AND_MAGICIAN, "trap_fill_percentage": 100, "reversed_controls_weight": "low",
               "forced_run_weight": "low"}

    def test_item_rule_refuses_traps_only_on_forbidden_locations(self) -> None:
        trap = self.world.create_item("Forced Run")
        filler = self.world.create_item("Simple Power")
        for loc in self.real_locations():
            with self.subTest(location=loc.name):
                self.assertEqual(loc.item_rule(trap), not is_trap_forbidden(loc.address))
                self.assertTrue(loc.item_rule(filler))

    def test_fill_never_puts_a_trap_on_forbidden_locations(self) -> None:
        for seed in range(10):
            with self.subTest(seed=seed):
                self.world_setup(seed)
                distribute_items_restrictive(self.multiworld)
                for loc in self.real_locations():
                    if is_trap_forbidden(loc.address):
                        self.assertNotIn(loc.item.name, TRAP_ITEMS, loc.name)


# ---- C4: number and kind of traps in the filler pool

class TestTrapCount(RaymanGenerationBase):
    options = TRAPS_ON

    def test_number_of_traps_is_the_percentage_of_fillers(self) -> None:
        for count in (0, 1, 10, 20, 33):
            with self.subTest(count=count):
                pool = self.world.create_filler_pool(count)
                self.assertEqual(len(pool), count)
                self.assertEqual(sum(item.name in TRAP_ITEMS for item in pool), round(count * 50 / 100))

    def test_both_traps_can_appear(self) -> None:
        names = {item.name for item in self.world.create_filler_pool(200)}
        self.assertLessEqual(TRAP_ITEMS, names)


