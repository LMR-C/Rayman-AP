class TestCoherence(unittest.TestCase):
    def test_every_effect_has_a_strategy(self) -> None:
        self.assertEqual(set(STRATEGIES), set(Effect))

    def test_every_item_builds_forward_and_reverse(self) -> None:
        for item in ITEMS:
            with self.subTest(item=item.name):
                strategy = STRATEGIES[item.effect]
                for ops in (strategy.forward(item), strategy.reverse(item)):
                    for address, op in ops:
                        self.assertIsInstance(address, int)
                        op.apply(0)  # catches a missing mask / value (None) in items.py
                        self.assertEqual(op.size, item.size.value)

    def test_every_counter_rule_is_used(self) -> None:
        counter_addresses = {item.address for item in ITEMS if item.effect is Effect.COUNTER}
        self.assertLessEqual(set(COUNTER_RULES), counter_addresses)
