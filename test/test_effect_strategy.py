class TestCounterStrategy(unittest.TestCase):
    def test_forward_adds_value(self) -> None:
        self.assertEqual(CounterStrategy().forward(COUNTER_ITEM), [(0x200, DeltaOperation(2, delta=3))])

    def test_reverse_removes_value(self) -> None:
        self.assertEqual(CounterStrategy().reverse(COUNTER_ITEM), [(0x200, DeltaOperation(2, delta=-3))])

    def test_applied_once(self) -> None:
        self.assertTrue(CounterStrategy.apply_once)

    def test_life_is_capped_at_99(self) -> None:
        life = ITEM_NAME_TABLE["Life"]
        for ops in (CounterStrategy().forward(life), CounterStrategy().reverse(life)):
            with self.subTest(ops=ops):
                (_, op), = ops
                self.assertEqual(op.cap, 99)

    def test_forward_and_reverse_can_be_merged(self) -> None:
        # Same cap on both sides, otherwise DeltaOperation.merge raises
        life = ITEM_NAME_TABLE["Life"]
        (_, forward), = CounterStrategy().forward(life)
        (_, reverse), = CounterStrategy().reverse(life)
        forward.merge(reverse)
        self.assertEqual(forward.delta, 0)

    def test_new_operations_on_each_call(self) -> None:
        # merge mutates in place: strategies must never share instances between calls
        (_, first), = CounterStrategy().forward(COUNTER_ITEM)
        (_, second), = CounterStrategy().forward(COUNTER_ITEM)
        self.assertIsNot(first, second)


