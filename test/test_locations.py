import unittest

from ..items import ITEM_ID_TABLE, ITEM_NAME_TO_ID
from ..locations import get_location_table

LOCATIONS = get_location_table()
MAIN_RAM_SIZE = 0x200000  # PS1 main RAM: 2 MB

# Location id ranges (docs/modelling.md) whose vanilla reward is always the same item
VANILLA_ITEM_BY_ID_RANGE = {
    1: "Cage",  # 1xxx: cages
    4: "Life Status",  # 4xxx: life status
}


class TestLocationsCoherence(unittest.TestCase):
    def test_vanilla_items_exist(self) -> None:
        for loc in LOCATIONS:
            if loc.vanilla_item is not None:
                with self.subTest(location=loc.name):
                    self.assertIn(loc.vanilla_item, ITEM_ID_TABLE)

    def test_vanilla_item_matches_id_range(self) -> None:
        for loc in LOCATIONS:
            expected = VANILLA_ITEM_BY_ID_RANGE.get(loc.id // 1000)
            if expected is not None:
                with self.subTest(location=loc.name):
                    self.assertEqual(loc.vanilla_item, ITEM_NAME_TO_ID[expected])

    def test_mask_fits_in_size(self) -> None:
        # The client reads ``size`` bytes: a wider mask can never match
        for loc in LOCATIONS:
            with self.subTest(location=loc.name):
                self.assertLess(loc.mask, 1 << (8 * loc.size.value))

    def test_address_in_main_ram(self) -> None:
        # The client reads the "MainRAM" domain: an address outside makes the whole read fail
        for loc in LOCATIONS:
            with self.subTest(location=loc.name):
                self.assertLess(loc.address + loc.size.value, MAIN_RAM_SIZE + 1)

    def test_location_ids_are_unique(self) -> None:
        ids = [loc.id for loc in LOCATIONS]
        self.assertEqual(len(ids), len(set(ids)))
