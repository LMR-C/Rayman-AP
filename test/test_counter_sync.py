class TestItemCounter(unittest.TestCase):
    def test_new_items_write_counter(self) -> None:
        ops = build_ram_operations([LIFE, FIST], 0, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS], SetOperation(ITEM_COUNTER_SIZE, value=2))
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS].apply(0), 2)

    def test_counter_only_moves_to_received_count(self) -> None:
        ops = build_ram_operations([LIFE, LIFE, LIFE], 1, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS], SetOperation(ITEM_COUNTER_SIZE, value=3))
        self.assertEqual(ops[LIFE_ADDRESS], DeltaOperation(1, delta=2, cap=99))

    def test_counter_up_to_date_no_counter_op(self) -> None:
        ops = build_ram_operations([LIFE, LIFE], 2, set(), set())
        self.assertNotIn(ITEM_COUNTER_ADDRESS, ops)
        self.assertEqual(ops, {})

    def test_no_item_no_counter_op(self) -> None:
        self.assertEqual(build_ram_operations([], 0, set(), set()), {})

    def test_counter_above_received_no_op_and_no_consumable(self) -> None:
        # Reconnection with a RAM counter ahead of items_received: never written back, nothing re-given
        ops = build_ram_operations([LIFE, CAGE], 5, set(), set())
        self.assertNotIn(ITEM_COUNTER_ADDRESS, ops)
        self.assertFalse(any(isinstance(op, DeltaOperation) for op in ops.values()))

    def test_bit_item_applied_whatever_the_counter(self) -> None:
        for counter in (0, 1, 5):
            with self.subTest(counter=counter):
                ops = build_ram_operations([FIST], counter, set(), set())
                self.assertEqual(ops[POWER_ADDRESS], MaskOperation(1, set_mask=0x01))

    def test_counter_items_below_counter_skipped(self) -> None:
        ops = build_ram_operations([CAGE, CAGE, CAGE], 2, set(), set())
        self.assertEqual(ops[CAGE_COUNTER_ADDRESS], DeltaOperation(1, delta=1))

    def test_counter_items_from_counter_applied(self) -> None:
        ops = build_ram_operations([CAGE, CAGE, CAGE], 0, set(), set())
        self.assertEqual(ops[CAGE_COUNTER_ADDRESS], DeltaOperation(1, delta=3))

    def test_counter_fits_in_two_bytes(self) -> None:
        ops = build_ram_operations([FIST] * 300, 0, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS].apply(0).to_bytes(ITEM_COUNTER_SIZE, "little"), b"\x2c\x01")


class TestDeliveredConsumables(unittest.TestCase):
    """RAM counter back to 0 (restart without saving) while the server remembers what was given."""

    def test_only_cage_is_restored(self) -> None:
        self.assertEqual(RESTORED_ITEM_IDS, {CAGE})

    def test_powers_not_given_again(self) -> None:
        for name in ("Simple Power", "Double Power", "Big Power"):
            with self.subTest(name=name):
                ops = build_ram_operations([ITEM_NAME_TO_ID[name]], 0, set(), set(), delivered_consumables=1)
                self.assertEqual(ops, {ITEM_COUNTER_ADDRESS: SetOperation(ITEM_COUNTER_SIZE, value=1)})

    def test_life_and_tings_not_given_again(self) -> None:
        ops = build_ram_operations([LIFE, TINGS], 0, set(), set(), delivered_consumables=2)
        self.assertNotIn(LIFE_ADDRESS, ops)
        self.assertNotIn(TINGS_ADDRESS, ops)

    def test_ram_counter_still_rewritten(self) -> None:
        ops = build_ram_operations([LIFE, TINGS], 0, set(), set(), delivered_consumables=2)
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS], SetOperation(ITEM_COUNTER_SIZE, value=2))

    def test_cage_given_again(self) -> None:
        ops = build_ram_operations([CAGE, LIFE, CAGE], 0, set(), set(), delivered_consumables=3)
        self.assertEqual(ops[CAGE_COUNTER_ADDRESS], DeltaOperation(1, delta=2))
        self.assertNotIn(LIFE_ADDRESS, ops)

    def test_new_consumable_given(self) -> None:
        ops = build_ram_operations([LIFE, LIFE], 0, set(), set(), delivered_consumables=1)
        self.assertEqual(ops[LIFE_ADDRESS], DeltaOperation(1, delta=1, cap=99))

    def test_ram_counter_ahead_of_server_wins(self) -> None:
        # Written in RAM, the server answer is still on its way: not given twice
        ops = build_ram_operations([LIFE], 1, set(), set(), delivered_consumables=0)
        self.assertNotIn(LIFE_ADDRESS, ops)

    def test_default_keeps_ram_counter_behaviour(self) -> None:
        ops = build_ram_operations([LIFE], 0, set(), set())
        self.assertEqual(ops[LIFE_ADDRESS], DeltaOperation(1, delta=1, cap=99))


class TestLocationResync(unittest.TestCase):
    def resync(self, checked: set[int]) -> dict:
        ops: dict = {}
        _add_location_resync_operations(ops, checked)
        return ops

    def test_checked_cage_flag_set(self) -> None:
        self.assertEqual(self.resync({CAGE_LOC_1})[CAGE_FLAG_ADDRESS], MaskOperation(1, set_mask=0x20))

    def test_checked_cage_adds_one_to_its_medallion(self) -> None:
        # Generated by Claude (Anthropic AI assistant): one cage = +1 on its level medallion
        self.assertEqual(
            self.resync({CAGE_LOC_1}),
            {
                CAGE_FLAG_ADDRESS: MaskOperation(1, set_mask=0x20),
                PPW_MEDALLION_ADDRESS: SetOperation(1, MEDALLION_STEP_PER_CAGE),
            },
        )

    def test_each_level_has_its_medallion_counter(self) -> None:
        # Generated by Claude (Anthropic AI assistant)
        for level, (cage_ids, address) in MEDALLION_COUNTERS.items():
            for cage_id in cage_ids:
                with self.subTest(level=level, cage=cage_id):
                    self.assertEqual(self.resync({cage_id})[address], SetOperation(1, MEDALLION_STEP_PER_CAGE))

    def test_cages_of_one_level_only_touch_its_medallion(self) -> None:
        # Generated by Claude (Anthropic AI assistant)
        for level, (cage_ids, address) in MEDALLION_COUNTERS.items():
            with self.subTest(level=level):
                ops = self.resync(set(cage_ids))
                self.assertEqual(ops[address], SetOperation(1, MEDALLION_STEP_PER_CAGE * len(cage_ids)))
                others = {other for _, other in MEDALLION_COUNTERS.values()} - {address}
                self.assertFalse(others & ops.keys())

    def test_betilla_ignored(self) -> None:
        # The flag IS the power bit: setting it would give the power
        self.assertEqual(self.resync({BETILLA_LOC}), {})

    def test_unknown_location_ignored(self) -> None:
        self.assertEqual(self.resync({999_999}), {})

    def test_two_locations_same_byte_merged(self) -> None:
        ops = self.resync({CAGE_LOC_1, CAGE_LOC_2})
        self.assertEqual(ops[CAGE_FLAG_ADDRESS], MaskOperation(1, set_mask=0x30))
        self.assertEqual(ops[PPW_MEDALLION_ADDRESS], SetOperation(1, 2 * MEDALLION_STEP_PER_CAGE))

    def test_resync_is_idempotent(self) -> None:
        op = self.resync({CAGE_LOC_1})[CAGE_FLAG_ADDRESS]
        self.assertEqual(op.apply(0x20), 0x20)
        self.assertEqual(op.apply(0x01), 0x21)

    def test_level_finished_unlocks_the_next_medallion(self) -> None:
        # Generated by Claude (Anthropic AI assistant): 7001 opens Fist Save, 7002 opens Bongo Hills
        self.assertEqual(self.resync({PPW_FINISHED})[0x1C34CC], SetOperation(1, 3))
        ops = self.resync({AL_FINISHED})
        self.assertEqual(ops[0x1C33B4], SetOperation(1, 3))
        self.assertEqual(ops[0x1C33AC], SetOperation(2, 0xB4))
        self.assertEqual(ops[0x1C33AE], SetOperation(2, 0xD7))

    def test_level_finished_flag_set(self) -> None:
        # Generated by Claude (Anthropic AI assistant)
        for loc_id, address in ((PPW_FINISHED, 0x1C3378), (AL_FINISHED, 0x1C338C), (SF_FINISHED, 0x1C33A0)):
            with self.subTest(location=loc_id):
                self.assertEqual(self.resync({loc_id})[address], MaskOperation(1, set_mask=0x3))

    def test_medallion_unlock_is_idempotent(self) -> None:
        # Generated by Claude (Anthropic AI assistant)
        for address, op in self.resync({PPW_FINISHED, AL_FINISHED}).items():
            with self.subTest(address=hex(address)):
                once = op.apply(0)
                self.assertEqual(op.apply(once), once)

    def test_medallion_counter_is_idempotent(self) -> None:
        # Generated by Claude (Anthropic AI assistant): the resync runs on EVERY tick with every checked location.
        # Applying two ticks must give the same RAM as one tick, as for the flags.
        ram = 0
        values = []
        for _tick in range(3):
            ram = build_ram_operations([], 0, {CAGE_LOC_1, CAGE_LOC_2}, set())[PPW_MEDALLION_ADDRESS].apply(ram)
            values.append(ram)
        self.assertEqual(values, [2 * MEDALLION_STEP_PER_CAGE] * 3)

    def test_resync_through_builder_keeps_cage_counter(self) -> None:
        # A checked cage gets its flag back and its +1 on the medallion: the cage item counter is not touched
        ops = build_ram_operations([], 0, {CAGE_LOC_1}, set())
        self.assertNotIn(CAGE_COUNTER_ADDRESS, ops)
        self.assertEqual(ops[CAGE_FLAG_ADDRESS], MaskOperation(1, set_mask=0x20))
        self.assertEqual(ops[PPW_MEDALLION_ADDRESS], SetOperation(1, MEDALLION_STEP_PER_CAGE))
