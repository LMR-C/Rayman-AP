class TestItemCounter(unittest.TestCase):
    def test_new_items_write_counter(self) -> None:
        ops = build_ram_operations([LIFE, FIST], 0, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS], SetOperation(ITEM_COUNTER_SIZE, value=2))
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS].apply(0), 2)

    def test_counter_only_moves_to_received_count(self) -> None:
        ops = build_ram_operations([LIFE, LIFE, LIFE], 1, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS], SetOperation(ITEM_COUNTER_SIZE, value=3))
        self.assertEqual(ops[LIFE_ADDRESS], DeltaOperation(1, delta=2, cap=99))

    def test_counter_up_to_date_no_counter_op(self) -> None:
        ops = build_ram_operations([LIFE, LIFE], 2, set(), set())
        self.assertNotIn(ITEM_COUNTER_ADDRESS, ops)
        self.assertEqual(ops, {})

    def test_no_item_no_counter_op(self) -> None:
        self.assertEqual(build_ram_operations([], 0, set(), set()), {})

    def test_counter_above_received_no_op_and_no_consumable(self) -> None:
        # Reconnection with a RAM counter ahead of items_received: never written back, nothing re-given
        ops = build_ram_operations([LIFE, CAGE], 5, set(), set())
        self.assertNotIn(ITEM_COUNTER_ADDRESS, ops)
        self.assertFalse(any(isinstance(op, DeltaOperation) for op in ops.values()))

    def test_bit_item_applied_whatever_the_counter(self) -> None:
        for counter in (0, 1, 5):
            with self.subTest(counter=counter):
                ops = build_ram_operations([FIST], counter, set(), set())
                self.assertEqual(ops[POWER_ADDRESS], MaskOperation(1, set_mask=0x01))

    def test_counter_items_below_counter_skipped(self) -> None:
        ops = build_ram_operations([CAGE, CAGE, CAGE], 2, set(), set())
        self.assertEqual(ops[CAGE_COUNTER_ADDRESS], DeltaOperation(1, delta=1))

    def test_counter_items_from_counter_applied(self) -> None:
        ops = build_ram_operations([CAGE, CAGE, CAGE], 0, set(), set())
        self.assertEqual(ops[CAGE_COUNTER_ADDRESS], DeltaOperation(1, delta=3))

    def test_counter_fits_in_two_bytes(self) -> None:
        ops = build_ram_operations([FIST] * 300, 0, set(), set())
        self.assertEqual(ops[ITEM_COUNTER_ADDRESS].apply(0).to_bytes(ITEM_COUNTER_SIZE, "little"), b"\x2c\x01")


class TestDeliveredConsumables(unittest.TestCase):
    """RAM counter back to 0 (restart without saving) while the server remembers what was given."""

