class TestRuleObjects(RaymanTestBase):
    """Each rule of rules.py, resolved on the world and evaluated on a state."""

    options = RULE_OPTIONS

    def check(self, rule, state) -> bool:
        return rule.resolve(self.world)(state)

    def event(self, name: str) -> RaymanItem:
        return RaymanItem(name, ItemClassification.progression, None, self.player)

    def test_none_is_always_true(self) -> None:
        self.assertTrue(self.check(rules.none, self.state_with()))

    def test_pink_plant_woods_is_always_open(self) -> None:
        self.assertTrue(self.check(rules.can_access_pink_plant_wood, self.state_with()))

    def test_power_rules_need_their_own_item(self) -> None:
        power_rules = {
            FIST: rules.has_fist,
            HANG: rules.has_hang,
            GRAPPLING: rules.has_grappling_fist,
            HELICOPTER: rules.has_helicopter,
        }
        for item, rule in power_rules.items():
            with self.subTest(item=item):
                self.assertFalse(self.check(rule, self.state_with()))
                self.assertTrue(self.check(rule, self.state_with(item)))
                others = [other for other in power_rules if other != item]
                self.assertFalse(self.check(rule, self.state_with(*others)))

    def test_magic_seed_rule_needs_the_seed(self) -> None:
        self.assertFalse(self.check(rules.has_magic_seed, self.state_with(FIST, HANG, GRAPPLING, HELICOPTER)))
        self.assertTrue(self.check(rules.has_magic_seed, self.state_with(SEED)))

    def test_level_access_rules_need_the_previous_level_event(self) -> None:
        level_rules = {
            "Pink Plant Woods finished event item": rules.can_access_anguish_lagoon,
            "Anguish Lagoon finished event item": rules.can_access_swamps_of_forgetfulness,
            "The Swamps of Forgetfulness finished event item": rules.can_acess_moskito_nest,
        }
        for event_name, rule in level_rules.items():
            with self.subTest(event=event_name):
                state = self.state_with()
                self.assertFalse(self.check(rule, state))
                state.collect(self.event(event_name), prevent_sweep=True)
                self.assertTrue(self.check(rule, state))


