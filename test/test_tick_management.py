def trap_ctx(*received: int) -> TickContext:
    """Neutral tick whose received items, in order, are ``received``."""
    return TickContext(
        {**NEUTRAL_STATE, "world_id": 0, "level_id": 0, "pos_x": 0, "pos_y": 0},
        frozenset(received),
        frozenset(),
        {},
        dict(VANILLA_SLOT_DATA),
        received_order=tuple(received),
    )


class TestTraps(EmptyTablesTestCase):
    """Trap life cycle in plan_tick with the real TRAPS (FREE_OPERATIONS emptied)."""

    def test_no_trap_received_no_trap_state(self) -> None:
        plan = plan_tick(trap_ctx(ITEM), frozenset(), TrapState(), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=1))
        self.assertEqual(plan.raw_ops, ())

    def test_new_trap_starts_at_once(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED), frozenset(), TrapState(), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=1, queue=(), active=REVERSED, remaining_s=30.0))
        self.assertEqual(plan.raw_ops, (REVERSED_ON,))

    def test_trap_already_seen_is_not_started_again(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED), frozenset(), TrapState(seen=1), 1.0)
        self.assertIsNone(plan.traps.active)
        self.assertEqual(plan.raw_ops, ())

    def test_active_trap_counts_down_and_stays_applied(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED), frozenset(), TrapState(1, (), REVERSED, 30.0), 0.5)
        self.assertEqual(plan.traps.remaining_s, 29.5)
        self.assertEqual(plan.raw_ops, (REVERSED_ON,))

    def test_trap_ends_and_is_restored(self) -> None:
        plan = plan_tick(trap_ctx(FORCED_RUN), frozenset(), TrapState(1, (), FORCED_RUN, 0.5), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=1))
        self.assertEqual(plan.raw_ops, (FORCED_RUN_OFF,))

    def test_two_traps_the_second_waits_in_the_queue(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED, FORCED_RUN), frozenset(), TrapState(), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=2, queue=(FORCED_RUN,), active=REVERSED, remaining_s=30.0))
        self.assertEqual(plan.raw_ops, (REVERSED_ON,))

    def test_next_trap_starts_the_tick_the_first_ends(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED, FORCED_RUN), frozenset(), TrapState(2, (FORCED_RUN,), REVERSED, 1.0), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=2, queue=(), active=FORCED_RUN, remaining_s=5.0))
        self.assertEqual(plan.raw_ops, (REVERSED_OFF, FORCED_RUN_ON))

    def test_trap_received_while_another_is_active_is_queued(self) -> None:
        plan = plan_tick(trap_ctx(REVERSED, FORCED_RUN), frozenset(), TrapState(1, (), REVERSED, 10.0), 1.0)
        self.assertEqual(plan.traps, TrapState(seen=2, queue=(FORCED_RUN,), active=REVERSED, remaining_s=9.0))

    def test_same_trap_twice_keeps_the_bit_set_between_both(self) -> None:
        # Restore and apply of the same bit in one tick: the set wins at merge (MaskOperation)
        plan = plan_tick(trap_ctx(REVERSED, REVERSED), frozenset(), TrapState(2, (REVERSED,), REVERSED, 1.0), 1.0)
        self.assertEqual(plan.traps.active, REVERSED)
        op = build_ram_operations([], 0, set(), set(), raw_ops=plan.raw_ops)[TRAP_ADDRESS]
        self.assertEqual(op.apply(0x20), 0x20)

    def test_trap_that_cannot_start_waits_without_counting_down(self) -> None:
        blocked = TrapSpec(
            REVERSED, 30.0, apply=lambda c: [REVERSED_ON], restore=lambda c: [REVERSED_OFF], can_start=lambda c: False
        )
        with patch.dict(f"{TICK_MANAGEMENT}.TRAPS", {REVERSED: blocked}):
            plan = plan_tick(trap_ctx(REVERSED), frozenset(), TrapState(1, (), REVERSED, 30.0), 1.0)
            self.assertEqual(plan.traps.remaining_s, 30.0)
            queued = plan_tick(trap_ctx(REVERSED), frozenset(), TrapState(), 1.0)
            self.assertEqual(queued.traps, TrapState(seen=1, queue=(REVERSED,)))
            self.assertEqual(queued.raw_ops, ())


class TestTickTrackerTraps(EmptyTablesTestCase):
    """dt given to plan_tick by TickTracker. Generated by Claude (Anthropic AI assistant)."""

    def test_elapsed_time_counted_down(self) -> None:
        now = [100.0]
        tracker = TickTracker(clock=lambda: now[0])
        tracker.plan(trap_ctx(REVERSED))
        now[0] += 0.25
        tracker.plan(trap_ctx(REVERSED))
        self.assertEqual(tracker.traps.remaining_s, 29.75)

    def test_long_pause_counts_one_second_at_most(self) -> None:
        now = [100.0]
        tracker = TickTracker(clock=lambda: now[0])
        tracker.plan(trap_ctx(FORCED_RUN))
        now[0] += 60.0  # emulator paused
        tracker.plan(trap_ctx(FORCED_RUN))
        self.assertEqual(tracker.traps.active, FORCED_RUN)
        self.assertEqual(tracker.traps.remaining_s, 4.0)

    def test_trap_ends_after_its_duration(self) -> None:
        now = [100.0]
        tracker = TickTracker(clock=lambda: now[0])
        tracker.plan(trap_ctx(FORCED_RUN))
        for _ in range(5):
            now[0] += 1.0
            plan = tracker.plan(trap_ctx(FORCED_RUN))
        self.assertIsNone(tracker.traps.active)
        self.assertEqual(plan.raw_ops, (FORCED_RUN_OFF,))


LIFE_COUNTER_ADDRESS = 0x1E4D50
TINGS_COUNTER_ADDRESS = 0x1E4D56
CONTINUE_COUNTER_ADDRESS = 0x1E5A10
STARTING_LIFE_APPLIED_ADDRESS = 0x1F9B20
CONTINUE_APPLIED_ADDRESS = 0x1F9B21


@patch(f"{TICK_MANAGEMENT}.PREVIOUS_CONTINUE", 5)
class TestOptionFreeOperations(unittest.TestCase):
    """Options applied by the real FREE_OPERATIONS. Generated by Claude (Anthropic AI assistant)."""

    def ops(self, slot_data: dict | None = None, **state: int) -> list:
        ctx = TickContext(
            {**NEUTRAL_STATE, "world_id": 0, "level_id": 0, "pos_x": 0, "pos_y": 0, **state},
            frozenset(),
            frozenset(),
            {},
            {**VANILLA_SLOT_DATA, **(slot_data or {})},
        )
        return list(plan_tick(ctx, frozenset()).raw_ops)

    def test_vanilla_options_write_nothing(self) -> None:
        ops = self.ops()
        for address in (
            LIFE_COUNTER_ADDRESS,
            TINGS_COUNTER_ADDRESS,
            CONTINUE_COUNTER_ADDRESS,
            STARTING_LIFE_APPLIED_ADDRESS,
            CONTINUE_APPLIED_ADDRESS,
        ):
            with self.subTest(address=hex(address)):
                self.assertNotIn(address, dict(ops))

    def test_starting_life_applied_once(self) -> None:
        ops = self.ops({"number_of_starting_life": 7})
        self.assertIn((LIFE_COUNTER_ADDRESS, SetOperation(1, 7)), ops)
        self.assertIn((STARTING_LIFE_APPLIED_ADDRESS, SetOperation(1, 1)), ops)

    def test_starting_life_not_applied_again(self) -> None:
        self.assertNotIn(
            LIFE_COUNTER_ADDRESS, dict(self.ops({"number_of_starting_life": 7}, starting_life_option_applied=1))
        )

    def test_starting_life_waits_for_the_default_three_lives(self) -> None:
        self.assertNotIn(LIFE_COUNTER_ADDRESS, dict(self.ops({"number_of_starting_life": 7}, life_counter=2)))

    def test_continue_used_allows_the_starting_life_again(self) -> None:
        ops = self.ops(continue_counter=4)  # PREVIOUS_CONTINUE = 5
        self.assertIn((STARTING_LIFE_APPLIED_ADDRESS, SetOperation(1, 0)), ops)

    def test_no_continue_used_keeps_the_flag(self) -> None:
        self.assertNotIn((STARTING_LIFE_APPLIED_ADDRESS, SetOperation(1, 0)), self.ops(continue_counter=5))

    def test_number_of_continue_applied_once(self) -> None:
        ops = self.ops({"number_of_continue": 9})
        self.assertIn((CONTINUE_COUNTER_ADDRESS, SetOperation(1, 9)), ops)
        self.assertIn((CONTINUE_APPLIED_ADDRESS, SetOperation(1, 1)), ops)
        self.assertNotIn(
            CONTINUE_COUNTER_ADDRESS, dict(self.ops({"number_of_continue": 9}, number_continue_option_applied=1))
        )

    def test_tings_give_a_life_at_the_option_threshold(self) -> None:
        ops = self.ops({"number_of_tings_to_get_a_new_life": 50}, tings_counter=53, life_counter=4)
        self.assertIn((LIFE_COUNTER_ADDRESS, SetOperation(1, 5)), ops)
        self.assertIn((TINGS_COUNTER_ADDRESS, SetOperation(1, 3)), ops)

    def test_tings_below_the_threshold_give_nothing(self) -> None:
        ops = self.ops({"number_of_tings_to_get_a_new_life": 50}, tings_counter=49)
        self.assertNotIn(TINGS_COUNTER_ADDRESS, dict(ops))
