@patch(f"{TICK_MANAGEMENT}.FORCE_WINDOWS", ())
@patch(f"{TICK_MANAGEMENT}.GATED_LOCATIONS", GATE)
class TestTickTracker(unittest.TestCase):
    def setUp(self) -> None:
        self.tracker = TickTracker()

    def test_starts_disarmed(self) -> None:
        self.assertEqual(self.tracker.armed, frozenset())

    def test_full_betilla_sequence(self) -> None:
        # Enters the zone with the power: not armed yet, the bit is cleared
        plan = self.tracker.plan(make_ctx(zone=True, received=True, missing=True, bit=True))
        self.assertIn(LOCATION, plan.banned_locations)
        self.assertEqual(self.tracker.armed, frozenset())
        # Bit read at 0: armed
        plan = self.tracker.plan(make_ctx(zone=True, received=True, missing=True, bit=False))
        self.assertEqual(self.tracker.armed, frozenset({LOCATION}))
        # Betilla sets the bit: the location can go to the server
        plan = self.tracker.plan(make_ctx(zone=True, received=True, missing=True, bit=True))
        self.assertNotIn(LOCATION, plan.banned_locations)
        self.assertEqual(plan.to_clear, frozenset())
        # Server confirmed: the rule stops and the forward comes back
        plan = self.tracker.plan(make_ctx(zone=True, received=True, missing=False))
        assert_plan(self, plan)
        self.assertEqual(self.tracker.armed, frozenset())

    def test_turning_back_never_allows_false_check(self) -> None:
        self.tracker.plan(make_ctx(zone=True, received=True, missing=True, bit=False))
        self.assertEqual(self.tracker.armed, frozenset({LOCATION}))
        self.tracker.plan(make_ctx(zone=False, received=True, missing=True, bit=False))
        # The forward puts the bit back to 1 out of the zone, then the player comes back
        plan = self.tracker.plan(make_ctx(zone=False, received=True, missing=True, bit=True))
        self.assertIn(LOCATION, plan.banned_locations)
        plan = self.tracker.plan(make_ctx(zone=True, received=True, missing=True, bit=True))
        self.assertIn(LOCATION, plan.banned_locations)
        self.assertEqual(plan.to_clear, frozenset({ITEM}))
