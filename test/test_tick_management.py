def in_zone(ctx: TickContext) -> bool:
    return ctx.state["zone"] == 1


def make_ctx(zone: bool, received: bool, missing: bool, bit: bool = False) -> TickContext:
    """Context of one tick. ``bit`` is the bit read for LOCATION, only known while it is missing."""
    return TickContext(
        state={"zone": int(zone)},
        received=frozenset({ITEM}) if received else frozenset(),
        missing=frozenset({LOCATION}) if missing else frozenset(),
        location_bits={LOCATION: bit} if missing else {},
        slot_data={},
    )


GATE = (GatedLocation(LOCATION, ITEM, in_zone),)
