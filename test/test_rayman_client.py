class FakeRam:
    """Replaces bizhawk.read / bizhawk.guarded_write with an in-memory RAM (missing addresses read as 0)."""

    def __init__(self) -> None:
        self.memory: dict[int, int] = {}
        self.guard_fails = False

    def set(self, address: int, data: bytes) -> None:
        for offset, byte in enumerate(data):
            self.memory[address + offset] = byte

    def get(self, address: int, size: int) -> bytes:
        return bytes(self.memory.get(address + offset, 0) for offset in range(size))

    async def read(self, _ctx, read_list) -> list[bytes]:
        return [self.get(address, size) for address, size, _domain in read_list]

    async def guarded_write(self, _ctx, write_list, guard_list) -> bool:
        if self.guard_fails:
            return False
        for address, expected, _domain in guard_list:
            if self.get(address, len(expected)) != bytes(expected):
                return False
        for address, value, _domain in write_list:
            self.set(address, bytes(value))
        return True


def make_ctx(missing_locations: set[int] | None = None, items: list[int] | None = None) -> MagicMock:
    ctx = MagicMock()
    ctx.server = object()
    ctx.slot = 1
    ctx.missing_locations = set() if missing_locations is None else missing_locations
    ctx.items_received = [NetworkItem(item_id, 0, 1) for item_id in items or []]
    ctx.check_locations = AsyncMock()
    return ctx


class TestGameWatcher(unittest.IsolatedAsyncioTestCase):
    def setUp(self) -> None:
        self.ram = FakeRam()
        self.read = AsyncMock(side_effect=self.ram.read)
        self.guarded_write = AsyncMock(side_effect=self.ram.guarded_write)
        patchers = [
            patch("worlds._bizhawk.read", self.read),
            patch("worlds._bizhawk.guarded_write", self.guarded_write),
            patch.dict("worlds.rayman.rayman_client.LOCATION_ID_TABLE", FAKE_LOCATION_ID_TABLE, clear=True),
            patch.dict("worlds.rayman.ram_operation.ITEM_ID_TABLE", FAKE_ITEM_ID_TABLE, clear=True),
        ]
        for patcher in patchers:
            patcher.start()
            self.addCleanup(patcher.stop)
        self.client = RaymanClient()

    # Guard

    async def test_no_server_does_nothing(self) -> None:
        ctx = make_ctx({LOCATION}, [BIT_ITEM])
        ctx.server = None
        await self.client.game_watcher(ctx)
        self.read.assert_not_awaited()
        ctx.check_locations.assert_not_awaited()

    async def test_no_slot_does_nothing(self) -> None:
        ctx = make_ctx({LOCATION}, [BIT_ITEM])
        ctx.slot = None
        await self.client.game_watcher(ctx)
        self.read.assert_not_awaited()
        ctx.check_locations.assert_not_awaited()

    # Locations

    async def test_location_checked_when_mask_set(self) -> None:
        self.ram.set(LOCATION_ADDRESS, b"\x80")
        ctx = make_ctx({LOCATION})
        await self.client.game_watcher(ctx)
        ctx.check_locations.assert_awaited_once_with({LOCATION})

    async def test_location_not_checked_when_mask_unset(self) -> None:
        self.ram.set(LOCATION_ADDRESS, b"\x7f")
        ctx = make_ctx({LOCATION})
        await self.client.game_watcher(ctx)
        ctx.check_locations.assert_awaited_once_with(set())

    # Items

    async def test_set_bit_written_with_guard(self) -> None:
        self.ram.set(BIT_ADDRESS, b"\x10")
        ctx = make_ctx(items=[BIT_ITEM])
        await self.client.game_watcher(ctx)
        self.guarded_write.assert_awaited_once_with(
            ctx.bizhawk_ctx,
            [(BIT_ADDRESS, b"\x11", "MainRAM")],
            [(BIT_ADDRESS, b"\x10", "MainRAM")],
        )
        self.assertEqual(self.client.items_index_counter, 1)

    async def test_set_bit_already_set_no_write(self) -> None:
        self.ram.set(BIT_ADDRESS, b"\x01")
        ctx = make_ctx(items=[BIT_ITEM])
        await self.client.game_watcher(ctx)
        self.guarded_write.assert_not_awaited()
        self.assertEqual(self.client.items_index_counter, 1)

    async def test_failed_guard_keeps_counter(self) -> None:
        self.ram.guard_fails = True
        ctx = make_ctx(items=[COUNTER_ITEM])
        await self.client.game_watcher(ctx)
        self.guarded_write.assert_awaited_once()
        self.assertEqual(self.client.items_index_counter, 0)
        self.assertEqual(self.ram.get(COUNTER_ADDRESS, 1), b"\x00")

    async def test_failed_guard_retried_next_tick(self) -> None:
        self.ram.guard_fails = True
        ctx = make_ctx(items=[COUNTER_ITEM])
        await self.client.game_watcher(ctx)
        self.ram.guard_fails = False
        await self.client.game_watcher(ctx)
        self.assertEqual(self.ram.get(COUNTER_ADDRESS, 1), b"\x01")
        self.assertEqual(self.client.items_index_counter, 1)

    async def test_add_not_applied_twice(self) -> None:
        ctx = make_ctx(items=[COUNTER_ITEM, COUNTER_ITEM])
        await self.client.game_watcher(ctx)
        await self.client.game_watcher(ctx)
        self.assertEqual(self.ram.get(COUNTER_ADDRESS, 1), b"\x02")
        self.guarded_write.assert_awaited_once()
        self.assertEqual(self.client.items_index_counter, 2)

    async def test_only_new_item_applied(self) -> None:
        ctx = make_ctx(items=[COUNTER_ITEM])
        await self.client.game_watcher(ctx)
        ctx.items_received.append(NetworkItem(COUNTER_ITEM, 0, 1))
        await self.client.game_watcher(ctx)
        self.assertEqual(self.ram.get(COUNTER_ADDRESS, 1), b"\x02")
        self.assertEqual(self.client.items_index_counter, 2)

    async def test_set_bit_restored_after_game_reset(self) -> None:
        # SET_BIT is idempotent: re-applied whenever the bit is missing, whatever the counter
        ctx = make_ctx(items=[BIT_ITEM])
        await self.client.game_watcher(ctx)
        self.ram.set(BIT_ADDRESS, b"\x00")
        await self.client.game_watcher(ctx)
        self.assertEqual(self.ram.get(BIT_ADDRESS, 1), b"\x01")

