FAKE_LOCATION_ID_TABLE = {
    BIT_LOC: fake_location(BIT_LOC, 0x1000, 0x01, vanilla_item=BIT),
    COUNTER_LOC_A: fake_location(COUNTER_LOC_A, 0x1001, 0x01, vanilla_item=COUNTER),
    COUNTER_LOC_B: fake_location(COUNTER_LOC_B, 0x1001, 0x02, vanilla_item=COUNTER),
    NO_VANILLA_LOC: fake_location(NO_VANILLA_LOC, 0x1002, 0x01),
    UNKNOWN_ITEM_LOC: fake_location(UNKNOWN_ITEM_LOC, 0x1003, 0x01, vanilla_item=999),
}

BUILDER = "worlds.rayman.client_stuff.operation_builder"


@patch.dict(f"{BUILDER}.ITEM_ID_TABLE", FAKE_ITEM_ID_TABLE, clear=True)
@patch.dict(f"{BUILDER}.LOCATION_ID_TABLE", FAKE_LOCATION_ID_TABLE, clear=True)
class TestBuildRamOperations(unittest.TestCase):
    def test_nothing_to_do(self) -> None:
        self.assertEqual(build_ram_operations([], 0, set(), set()), {})

    def test_items_only(self) -> None:
        self.assertEqual(build_ram_operations([BIT, COUNTER], 0, set(), set()), {
            0x100: MaskOperation(1, set_mask=0x04),
            0x200: DeltaOperation(1, delta=1),
        })

    def test_reverse_counter_location(self) -> None:
        self.assertEqual(build_ram_operations([], 0, set(), {COUNTER_LOC_A}), {0x200: DeltaOperation(1, delta=-1)})

    def test_reverse_bit_location(self) -> None:
        self.assertEqual(build_ram_operations([], 0, set(), {BIT_LOC}), {0x100: MaskOperation(1, clear_mask=0x04)})

    def test_two_reversed_locations_same_item_summed(self) -> None:
        ops = build_ram_operations([], 0, set(), {COUNTER_LOC_A, COUNTER_LOC_B})
        self.assertEqual(ops, {0x200: DeltaOperation(1, delta=-2)})

    def test_received_item_and_reversed_vanilla_cancel_out(self) -> None:
        # Counter received from AP while picking the vanilla counter location: +1 -1
        ops = build_ram_operations([COUNTER], 0, set(), {COUNTER_LOC_A})
        self.assertEqual(ops, {0x200: DeltaOperation(1, delta=0)})

    def test_received_bit_wins_over_reversed_vanilla(self) -> None:
        # Bit received from AP: kept even if its vanilla location is reversed
        ops = build_ram_operations([BIT], 0, set(), {BIT_LOC})
        self.assertEqual(ops[0x100].apply(0x00), 0x04)
        self.assertEqual(ops[0x100].apply(0x04), 0x04)

    def test_already_applied_counter_still_reversed(self) -> None:
        # counter_state only filters received items, never the reverse
        ops = build_ram_operations([COUNTER], 1, set(), {COUNTER_LOC_A})
        self.assertEqual(ops, {0x200: DeltaOperation(1, delta=-1)})

    def test_location_without_vanilla_item_ignored_silently(self) -> None:
        with self.assertNoLogs("OperationBuilder", level="WARNING"):
            self.assertEqual(build_ram_operations([], 0, set(), {NO_VANILLA_LOC}), {})

    def test_unknown_location_skipped_with_warning(self) -> None:
        with self.assertLogs("OperationBuilder", level="WARNING"):
            self.assertEqual(build_ram_operations([], 0, set(), {999}), {})

    def test_unknown_vanilla_item_skipped_with_warning(self) -> None:
        with self.assertLogs("OperationBuilder", level="WARNING"):
            self.assertEqual(build_ram_operations([], 0, set(), {UNKNOWN_ITEM_LOC}), {})

    def test_none_item_has_no_operation(self) -> None:
        self.assertEqual(build_ram_operations([NOTHING], 0, set(), set()), {})


