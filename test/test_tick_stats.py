import unittest
from unittest.mock import patch

from ..client_stuff.tick_stats import TickStats

PERF_COUNTER = "worlds.rayman.client_stuff.tick_stats.time.perf_counter"
LOGGER = "RaymanClient"


class TestTickStats(unittest.TestCase):
    def make_stats(self) -> TickStats:
        with patch(PERF_COUNTER, return_value=100.0):
            return TickStats()

    def test_fast_tick_logs_nothing(self) -> None:
        stats = self.make_stats()
        with patch(PERF_COUNTER, return_value=101.0), self.assertNoLogs(LOGGER, level="INFO"):
            stats.end_tick({"read_state": 0.01, "read_ops": 0.01})

    def test_slow_tick_warns_with_detail(self) -> None:
        stats = self.make_stats()
        with patch(PERF_COUNTER, return_value=101.0), self.assertLogs(LOGGER, level="WARNING") as logs:
            stats.end_tick({"read_state": 0.2, "write": 0.1})
        self.assertEqual(logs.records[0].getMessage(), "Slow tick: 300ms (read_state=200ms, write=100ms)")

    def test_durations_are_kept_until_the_summary(self) -> None:
        stats = self.make_stats()
        with patch(PERF_COUNTER, return_value=101.0):
            stats.end_tick({"read_state": 0.01})
            stats.end_tick({"read_state": 0.03})
        self.assertEqual(stats.durations, {"read_state": [0.01, 0.03]})

    def test_summary_when_period_is_over(self) -> None:
        stats = self.make_stats()
        with patch(PERF_COUNTER, return_value=101.0):
            stats.end_tick({"read_state": 0.01})
        with patch(PERF_COUNTER, return_value=130.0), self.assertLogs(LOGGER, level="INFO") as logs:
            stats.end_tick({"read_state": 0.03, "write": 0.02})
        self.assertEqual(logs.records[0].getMessage(),
                         "Timings | read_state: avg=20.0ms max=30.0ms n=2 | write: avg=20.0ms max=20.0ms n=1")

    def test_summary_resets_stats_and_period(self) -> None:
        stats = self.make_stats()
        with patch(PERF_COUNTER, return_value=130.0), self.assertLogs(LOGGER, level="INFO"):
            stats.end_tick({"read_state": 0.01})
        self.assertEqual(stats.durations, {})
        with patch(PERF_COUNTER, return_value=131.0), self.assertNoLogs(LOGGER, level="INFO"):
            stats.end_tick({"read_state": 0.01})
